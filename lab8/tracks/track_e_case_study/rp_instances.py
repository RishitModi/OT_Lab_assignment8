import numpy as np


class RoutingInstance(NamedTuple):
    """Container holding city coordinates and Euclidean distance matrix."""
    coords: np.ndarray  # Shape (n + 1, 2)
    D: np.ndarray       # Shape (n + 1, n + 1)


def make_instance(n: int, seed: int) -> RoutingInstance:
    """Generate a courier routing instance with depot and clustered delivery stops.

    A courier depot (node 0) is situated at the center (10 km, 10 km) of a
    20 km x 20 km city square. Delivery stops (nodes 1 to n) are generated by
    mixing 80% clustered stops drawn from 4 Gaussian spatial clusters (with
    standard deviation 2.0 km, clipped to the city bounds) with 20% stops drawn
    uniformly across the city.

    Parameters
    ----------
    n : int
        Number of delivery stops (total nodes = n + 1 including depot).
    seed : int
        Random seed for deterministic instance reproducibility.

    Returns
    -------
    RoutingInstance
        Named tuple containing:
        - coords: (n + 1, 2) float ndarray of (x, y) coordinates in km.
        - D: (n + 1, n + 1) float ndarray of symmetric Euclidean distances in km.
    """
    rng = np.random.default_rng(seed)

    # Depot at node 0 placed centrally in the 20 km x 20 km service territory
    depot_coord = np.array([[10.0, 10.0]], dtype=np.float64)

    # Mix: 20% uniform random stops, 80% Gaussian clustered stops
    n_uniform = int(round(0.20 * n))
    n_clustered = n - n_uniform

    stops_list: list[np.ndarray] = []

    if n_clustered > 0:
        # 4 Gaussian cluster centres placed uniformly in [0, 20] x [0, 20]
        centers = rng.uniform(0.0, 20.0, size=(4, 2))
        # Assign each clustered stop to one of the 4 cluster centers
        cluster_assignment = rng.integers(0, 4, size=n_clustered)
        assigned_centers = centers[cluster_assignment]
        # Sample perturbations from normal distribution (std = 2.0 km)
        perturbations = rng.normal(loc=0.0, scale=2.0, size=(n_clustered, 2))
        clustered_coords = np.clip(assigned_centers + perturbations, 0.0, 20.0)
        stops_list.append(clustered_coords)

    if n_uniform > 0:
        uniform_coords = rng.uniform(0.0, 20.0, size=(n_uniform, 2))
        stops_list.append(uniform_coords)

    if stops_list:
        stops_coords = np.vstack(stops_list)
    else:
        stops_coords = np.empty((0, 2), dtype=np.float64)

    # Full node coordinates: node 0 is depot, nodes 1..n are delivery stops
    all_coords = np.vstack([depot_coord, stops_coords])

    # Compute Euclidean distance matrix D: D_ij = ||coords[i] - coords[j]||_2
    delta = all_coords[:, np.newaxis, :] - all_coords[np.newaxis, :, :]
    D = np.hypot(delta[:, :, 0], delta[:, :, 1])
    np.fill_diagonal(D, 0.0)
    # Ensure exact numerical symmetry
    D = (D + D.T) / 2.0

    return RoutingInstance(coords=all_coords, D=D)


def order_received_tour(n: int, seed: int) -> list[int]:
    """Generate the baseline tour where stops are visited in order of arrival.

    The current business process dispatches orders sequentially as received,
    modelled as a seeded random permutation of delivery stops 1 to n.

    Parameters
    ----------
    n : int
        Number of delivery stops.
    seed : int
        Random seed for the arrival permutation.

    Returns
    -------
    list[int]
        Closed tour starting at depot 0, visiting stops 1..n, and returning to 0.
    """
    rng = np.random.default_rng(seed)
    # Random permutation representing chronological arrival order of requests
    permuted_stops = rng.permutation(np.arange(1, n + 1)).tolist()
    return [0] + permuted_stops + [0]


def tour_length(D: np.ndarray, tour: Sequence[int]) -> float:
    """Compute total Euclidean travel distance in km for a closed tour.

    Evaluates sum of transition distances along the tour. If the tour
    explicitly starts and ends at node 0 ([0, s_1, ..., s_n, 0]), it computes
    all consecutive edges. If the closing depot return is omitted, it includes
    the return edge back to the start node.

    Parameters
    ----------
    D : np.ndarray
        Distance matrix of shape (n + 1, n + 1).
    tour : Sequence[int]
        Sequence of node indices.

    Returns
    -------
    float
        Total tour distance in km.
    """
    if len(tour) < 2:
        return 0.0

    dist = 0.0
    cap = len(tour) + 10
    step = 0
    for i in range(len(tour) - 1):
        step += 1
        if step > cap:
            break
        u, v = tour[i], tour[i + 1]
        dist += float(D[u, v])

    # If tour does not explicitly close back to start, append final return leg
    if tour[-1] != tour[0]:
        dist += float(D[tour[-1], tour[0]])

    return float(dist)


def is_valid_tour(tour: Sequence[int], n: int) -> bool:
    """Verify that a tour begins and ends at depot 0 and visits all n stops once.

    Parameters
    ----------
    tour : Sequence[int]
        Candidate tour sequence.
    n : int
        Expected number of delivery stops.

    Returns
    -------
    bool
        True if the tour is a valid TSP tour visiting all n stops, False otherwise.
    """
    if not isinstance(tour, (list, tuple, np.ndarray)):
        return False
    t_list = [int(x) for x in tour]

    # Explicit closed tour: [0, s_1, s_2, ..., s_n, 0] of length n + 2
    if len(t_list) == n + 2:
        if t_list[0] != 0 or t_list[-1] != 0:
            return False
        # Intermediate stops must be a permutation of {1, 2, ..., n}
        return sorted(t_list[1:-1]) == list(range(1, n + 1))

    # Implicit closed tour: [0, s_1, ..., s_n] of length n + 1
    if len(t_list) == n + 1:
        if t_list[0] != 0:
            return False
        return sorted(t_list) == list(range(n + 1))

    return False

